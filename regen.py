#!/usr/bin/env python3
"""Generate register definitions for every GreenCoyote-Bay consumer from registers.yaml.

registers.yaml is the source of truth. This script emits address constants,
field positions, reset values, and enums into each consumer's language. It does
NOT emit the RTL always-blocks or the proxy's business logic -- those encode
behaviour (CAL_LOCK gating, BRAM address auto-increment, the xbar_update strobe)
that a table cannot express. What it does guarantee is that no address or bit
position is ever typed by hand in more than one place.

Targets
-------
    sv   greencoyote_regmap_pkg.sv     -> gcb-rtl/rtl/generated/
    hpp  greencoyote_regmap.hpp        -> gcb-host/include/generated/
    py   regmap.py                     -> gcb-host/proxy/generated/
    ts   registers.ts                  -> gcb-dashboard/src/generated/

Each target lands in its consumer repo automatically:
<out-root>/<repo>/<subdir>/<file>, where <out-root> defaults to the directory
that holds this spec repo (i.e. the parent of gcb-spec).

Usage
-----
    python regen.py --all                       # regenerate every consumer in place
    python regen.py --all --check               # CI: fail if any file is stale
    python regen.py --target sv                 # just gcb-rtl/rtl/generated/
    python regen.py --target hpp --out /tmp/x   # override the destination directory
    python regen.py --all --out-root /path/to/checkout   # non-default layout
    python regen.py --validate                  # validate registers.yaml, emit nothing

Exit codes: 0 ok, 1 validation error, 2 --check found a stale file.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("PyYAML required:  pip install pyyaml")

SPEC_DEFAULT = Path(__file__).with_name("registers.yaml")

BANNER = "DO NOT EDIT -- generated by regen.py from registers.yaml"

# Consumer repo that owns each target, and the path within that repo.
REPO = {
    "sv":  "gcb-rtl",
    "hpp": "gcb-host",
    "py":  "gcb-host",
    "ts":  "gcb-dashboard",
}

DEFAULT_SUBDIR = {
    "sv":  "rtl/generated",
    "hpp": "include/generated",
    "py":  "proxy/generated",
    "ts":  "src/generated",
}

FILENAME = {
    "sv":  "greencoyote_regmap_pkg.sv",
    "hpp": "greencoyote_regmap.hpp",
    "py":  "regmap.py",
    "ts":  "registers.ts",
}

# Default: the directory that contains gcb-spec (and its sibling consumer repos).
OUT_ROOT_DEFAULT = Path(__file__).resolve().parent.parent


def target_dest(target: str, out_root: Path, out: Path | None) -> Path:
    """Resolve where a target's generated file goes.

    `out` (from --out) overrides the directory outright; otherwise it is
    <out_root>/<repo>/<subdir>, so `--all` and a bare `--target` both land in
    the right consumer repo regardless of the current working directory.
    """
    directory = out if out is not None else out_root / REPO[target] / DEFAULT_SUBDIR[target]
    return directory / FILENAME[target]


# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------

def load(path: Path) -> dict:
    with path.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def implemented(reg: dict) -> bool:
    return reg.get("implemented", True) and reg.get("fields")


def msb_lsb(field: dict) -> tuple[int, int]:
    """Fields are written [msb, lsb]. Tolerate a single-int shorthand."""
    bits = field["bits"]
    if isinstance(bits, int):
        return bits, bits
    msb, lsb = bits
    return (msb, lsb) if msb >= lsb else (lsb, msb)


# ---------------------------------------------------------------------------
# Validation -- the part that would have caught the bug
# ---------------------------------------------------------------------------

def validate(spec: dict) -> list[str]:
    errs: list[str] = []
    space = spec["address_space"]
    addr_width = space["addr_width"]
    stride = space.get("stride", 4)
    max_addr = (1 << addr_width) - 1

    seen_offsets: dict[int, str] = {}
    truncated: dict[int, list[str]] = {}

    for reg in spec["registers"]:
        name, off = reg["name"], reg["offset"]

        if off % stride:
            errs.append(f"{name}: offset 0x{off:02X} is not {stride}-byte aligned")

        # DEFECT-001 class. An offset wider than the bus silently aliases.
        if off > max_addr:
            errs.append(
                f"{name}: offset 0x{off:02X} exceeds addr_width={addr_width} "
                f"(max 0x{max_addr:02X}); it would truncate to 0x{off & max_addr:02X}"
            )
        truncated.setdefault(off & max_addr, []).append(name)

        if off in seen_offsets:
            errs.append(f"{name}: offset 0x{off:02X} already used by {seen_offsets[off]}")
        seen_offsets[off] = name

        if not implemented(reg):
            continue

        # Bit-level checks.
        occupancy: dict[int, str] = {}
        for field in reg["fields"]:
            fname = field["name"]
            msb, lsb = msb_lsb(field)

            if msb > 31 or lsb < 0:
                errs.append(f"{name}.{fname}: bits [{msb}:{lsb}] outside 32-bit word")
                continue

            for bit in range(lsb, msb + 1):
                if bit in occupancy and not (
                    fname.startswith("RSVD") or occupancy[bit].startswith("RSVD")
                ):
                    errs.append(
                        f"{name}: bit {bit} claimed by both {occupancy[bit]} and {fname}"
                    )
                occupancy[bit] = fname

            reset = field.get("reset")
            if reset is not None:
                width = msb - lsb + 1
                if reset >= (1 << width):
                    errs.append(
                        f"{name}.{fname}: reset {reset:#x} does not fit in {width} bits"
                    )

            acc = field.get("access")
            if acc in ("rw", "rw_locked", "w1p") and not field.get("signal") \
                    and not fname.startswith("RSVD"):
                errs.append(f"{name}.{fname}: access={acc} needs a `signal:`")
            if acc == "ro" and "source" not in field and not fname.startswith("RSVD"):
                errs.append(f"{name}.{fname}: access=ro needs a `source:` (use null if hardwired)")

    # Report aliasing groups even when addr_width is correct, so a future
    # narrowing is caught immediately.
    for trunc, names in sorted(truncated.items()):
        if len(names) > 1:
            errs.append(
                f"address collision at 0x{trunc:02X} under addr_width={addr_width}: "
                + ", ".join(names)
            )

    return errs


# ---------------------------------------------------------------------------
# Emitters
# ---------------------------------------------------------------------------

def _hdr(spec: dict, comment: str) -> list[str]:
    return [
        f"{comment} {BANNER}",
        f"{comment} map_version: {spec['map_version']}",
        f"{comment} module: {spec['module']}",
        "",
    ]


def emit_sv(spec: dict) -> str:
    space = spec["address_space"]
    aw = space["addr_width"]
    out = _hdr(spec, "//")
    out += [
        "`ifndef GREENCOYOTE_REGMAP_PKG_SV",
        "`define GREENCOYOTE_REGMAP_PKG_SV",
        "",
        "package greencoyote_regmap_pkg;",
        "",
        f'    localparam string MAP_VERSION = "{spec["map_version"]}";',
        f"    localparam int    ADDR_WIDTH  = {aw};",
        f"    localparam logic [31:0] UNMAPPED_READ = 32'h{space['unmapped_read']:08X};",
        "",
        "    // ---- Register offsets ----",
    ]
    for reg in spec["registers"]:
        if not implemented(reg):
            out.append(f"    // {reg['name']:<24} 0x{reg['offset']:02X}  NOT IMPLEMENTED")
            continue
        out.append(
            f"    localparam logic [{aw-1}:0] ADDR_{reg['name']:<22} = "
            f"{aw}'h{reg['offset']:02X};"
        )

    out += ["", "    // ---- Field positions ----"]
    for reg in spec["registers"]:
        if not implemented(reg):
            continue
        out.append(f"    // {reg['name']} @ 0x{reg['offset']:02X}")
        for field in reg["fields"]:
            if field["name"].startswith("RSVD"):
                continue
            msb, lsb = msb_lsb(field)
            base = f"{reg['name']}_{field['name']}"
            out.append(f"    localparam int {base}_MSB = {msb};")
            out.append(f"    localparam int {base}_LSB = {lsb};")
            if (r := field.get("reset")) is not None:
                w = msb - lsb + 1
                out.append(f"    localparam logic [{w-1}:0] {base}_RST = {w}'h{r:X};")
        out.append("")

    # Enums as typedef'd localparams -- keeps them usable in assertions.
    out.append("    // ---- Field encodings ----")
    for reg in spec["registers"]:
        if not implemented(reg):
            continue
        for field in reg["fields"]:
            enum = field.get("enum")
            if not enum:
                continue
            msb, lsb = msb_lsb(field)
            w = msb - lsb + 1
            for val, label in enum.items():
                out.append(
                    f"    localparam logic [{w-1}:0] "
                    f"{reg['name']}_{field['name']}_{label} = {w}'h{val:X};"
                )
    out += ["", "endpackage", "", "`endif", ""]
    return "\n".join(out)


def emit_hpp(spec: dict) -> str:
    out = _hdr(spec, "//")
    out += [
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace greencoyote::regmap {",
        "",
        f'inline constexpr const char* kMapVersion = "{spec["map_version"]}";',
        f"inline constexpr uint32_t kUnmappedRead = 0x{spec['address_space']['unmapped_read']:08X}u;",
        "",
        "// ---- Register offsets ----",
    ]
    for reg in spec["registers"]:
        if not implemented(reg):
            out.append(f"// {reg['name']} @ 0x{reg['offset']:02X} -- NOT IMPLEMENTED")
            continue
        out.append(f"inline constexpr uint32_t k{reg['name']} = 0x{reg['offset']:02X}u;")

    out += ["", "// ---- Field accessors ----"]
    for reg in spec["registers"]:
        if not implemented(reg):
            continue
        out.append(f"// {reg['name']} @ 0x{reg['offset']:02X}")
        for field in reg["fields"]:
            if field["name"].startswith("RSVD"):
                continue
            msb, lsb = msb_lsb(field)
            width = msb - lsb + 1
            mask = ((1 << width) - 1) << lsb
            base = f"{reg['name']}_{field['name']}"
            acc = field.get("access", "rw")
            out.append(f"inline constexpr uint32_t k{base}Mask  = 0x{mask:08X}u;")
            out.append(f"inline constexpr int      k{base}Shift = {lsb};")
            out.append(
                f"inline constexpr uint32_t get{base}(uint32_t w) "
                f"{{ return (w & k{base}Mask) >> k{base}Shift; }}"
            )
            if acc in ("rw", "rw_locked", "wo", "w1p"):
                out.append(
                    f"inline constexpr uint32_t set{base}(uint32_t w, uint32_t v) "
                    f"{{ return (w & ~k{base}Mask) | ((v << k{base}Shift) & k{base}Mask); }}"
                )
            if acc == "w1p":
                out.append(f"// NOTE: {base} is write-1-pulse; it always reads back 0.")
            if acc == "ro":
                out.append(f"// NOTE: {base} is read-only.")
        out.append("")
    out += ["}  // namespace greencoyote::regmap", ""]
    return "\n".join(out)


def emit_py(spec: dict) -> str:
    out = _hdr(spec, "#")
    out += [
        '"""Register map for the GreenCoyote-Bay MMIO proxy."""',
        "",
        "from __future__ import annotations",
        "from dataclasses import dataclass",
        "",
        f'MAP_VERSION = "{spec["map_version"]}"',
        f"UNMAPPED_READ = 0x{spec['address_space']['unmapped_read']:08X}",
        "",
        "",
        "@dataclass(frozen=True)",
        "class Field:",
        "    name: str",
        "    msb: int",
        "    lsb: int",
        "    access: str",
        "    reset: int | None = None",
        "    enum: dict | None = None",
        "    description: str = ''",
        "",
        "    @property",
        "    def mask(self) -> int:",
        "        return ((1 << (self.msb - self.lsb + 1)) - 1) << self.lsb",
        "",
        "    def get(self, word: int) -> int:",
        "        return (word & self.mask) >> self.lsb",
        "",
        "    def set(self, word: int, value: int) -> int:",
        "        return (word & ~self.mask) | ((value << self.lsb) & self.mask)",
        "",
        "    def decode(self, word: int):",
        "        raw = self.get(word)",
        "        return self.enum.get(raw, raw) if self.enum else raw",
        "",
        "",
        "@dataclass(frozen=True)",
        "class Register:",
        "    name: str",
        "    offset: int",
        "    domain: str",
        "    fields: tuple[Field, ...]",
        "    description: str = ''",
        "",
        "    def decode(self, word: int) -> dict:",
        "        return {f.name: f.decode(word) for f in self.fields",
        "                if not f.name.startswith('RSVD')}",
        "",
        "",
        "REGISTERS: dict[str, Register] = {",
    ]
    for reg in spec["registers"]:
        if not implemented(reg):
            continue
        out.append(f'    "{reg["name"]}": Register(')
        out.append(f'        name="{reg["name"]}", offset=0x{reg["offset"]:02X}, '
                   f'domain="{reg.get("domain", "")}",')
        desc = (reg.get("description") or "").replace('"', "'").strip()
        out.append(f'        description="{desc}",')
        out.append("        fields=(")
        for field in reg["fields"]:
            msb, lsb = msb_lsb(field)
            reset = field.get("reset")
            enum = field.get("enum")
            fdesc = (field.get("description") or "").replace('"', "'").strip()
            out.append(
                f'            Field("{field["name"]}", {msb}, {lsb}, '
                f'"{field.get("access", "rw")}", '
                f"{reset if reset is None else hex(reset)}, "
                f"{enum!r}, "
                f'"{fdesc}"),'
            )
        out.append("        ),")
        out.append("    ),")
    out += [
        "}",
        "",
        "BY_OFFSET: dict[int, Register] = {r.offset: r for r in REGISTERS.values()}",
        "",
        "",
        "def decode(offset: int, word: int) -> dict:",
        '    """Decode a raw MMIO word. Returns {} for an unmapped offset."""',
        "    reg = BY_OFFSET.get(offset)",
        "    return reg.decode(word) if reg else {}",
        "",
    ]
    return "\n".join(out)


def emit_ts(spec: dict) -> str:
    out = _hdr(spec, "//")
    out += [
        f'export const MAP_VERSION = "{spec["map_version"]}";',
        f"export const UNMAPPED_READ = 0x{spec['address_space']['unmapped_read']:08X};",
        "",
        "export interface RegField {",
        "  name: string;",
        "  msb: number;",
        "  lsb: number;",
        "  access: string;",
        "  reset?: number;",
        "  enum?: Record<number, string>;",
        "}",
        "",
        "export interface Register {",
        "  name: string;",
        "  offset: number;",
        "  domain: string;",
        "  fields: RegField[];",
        "}",
        "",
        "export const REGISTERS: Register[] = [",
    ]
    for reg in spec["registers"]:
        if not implemented(reg):
            continue
        out.append("  {")
        out.append(f'    name: "{reg["name"]}",')
        out.append(f"    offset: 0x{reg['offset']:02X},")
        out.append(f'    domain: "{reg.get("domain", "")}",')
        out.append("    fields: [")
        for field in reg["fields"]:
            msb, lsb = msb_lsb(field)
            parts = [
                f'name: "{field["name"]}"',
                f"msb: {msb}",
                f"lsb: {lsb}",
                f'access: "{field.get("access", "rw")}"',
            ]
            if (r := field.get("reset")) is not None:
                parts.append(f"reset: 0x{r:X}")
            if enum := field.get("enum"):
                pairs = ", ".join(f'{k}: "{v}"' for k, v in enum.items())
                parts.append(f"enum: {{ {pairs} }}")
            out.append("      { " + ", ".join(parts) + " },")
        out.append("    ],")
        out.append("  },")
    out += [
        "];",
        "",
        "export const BY_OFFSET: Record<number, Register> = Object.fromEntries(",
        "  REGISTERS.map((r) => [r.offset, r]),",
        ");",
        "",
        "export function fieldValue(word: number, f: RegField): number {",
        "  const mask = ((1 << (f.msb - f.lsb + 1)) - 1) << f.lsb;",
        "  return (word & mask) >>> f.lsb;",
        "}",
        "",
        "export function decode(offset: number, word: number): Record<string, number | string> {",
        "  const reg = BY_OFFSET[offset];",
        "  if (!reg) return {};",
        "  const out: Record<string, number | string> = {};",
        "  for (const f of reg.fields) {",
        '    if (f.name.startsWith("RSVD")) continue;',
        "    const raw = fieldValue(word, f);",
        "    out[f.name] = f.enum?.[raw] ?? raw;",
        "  }",
        "  return out;",
        "}",
        "",
    ]
    return "\n".join(out)


EMITTERS = {"sv": emit_sv, "hpp": emit_hpp, "py": emit_py, "ts": emit_ts}


# ---------------------------------------------------------------------------
# Driver
# ---------------------------------------------------------------------------

def write_or_check(text: str, dest: Path, check: bool) -> int:
    if check:
        if not dest.exists():
            print(f"STALE  {dest} does not exist", file=sys.stderr)
            return 2
        cur = dest.read_text(encoding="utf-8")
        if hashlib.sha256(cur.encode()).digest() != hashlib.sha256(text.encode()).digest():
            print(f"STALE  {dest} differs from registers.yaml", file=sys.stderr)
            return 2
        print(f"ok     {dest}")
        return 0
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote  {dest}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--spec", type=Path, default=SPEC_DEFAULT)
    ap.add_argument("--target", choices=sorted(EMITTERS))
    ap.add_argument("--all", action="store_true", help="emit every target")
    ap.add_argument("--out", type=Path,
                    help="override output directory (single --target only)")
    ap.add_argument("--out-root", type=Path, default=OUT_ROOT_DEFAULT,
                    help="directory holding the consumer repos (gcb-rtl, gcb-host, "
                         "gcb-dashboard); each target lands in <root>/<repo>/<subdir>. "
                         f"Default: {OUT_ROOT_DEFAULT}")
    ap.add_argument("--check", action="store_true",
                    help="compare against existing files, write nothing (CI mode)")
    ap.add_argument("--validate", action="store_true", help="validate only")
    args = ap.parse_args()

    spec = load(args.spec)

    errs = validate(spec)
    if errs:
        print(f"{len(errs)} validation error(s) in {args.spec}:", file=sys.stderr)
        for e in errs:
            print(f"  - {e}", file=sys.stderr)
        return 1
    print(f"validated {args.spec}  (map_version {spec['map_version']}, "
          f"{sum(1 for r in spec['registers'] if implemented(r))} implemented, "
          f"{sum(1 for r in spec['registers'] if not implemented(r))} stub)")

    if args.validate:
        return 0

    if args.all:
        if args.out:
            ap.error("--out is for a single --target; use --out-root with --all")
        rc = 0
        for target, emit in EMITTERS.items():
            dest = target_dest(target, args.out_root, None)
            rc = max(rc, write_or_check(emit(spec), dest, args.check))
        return rc

    if not args.target:
        ap.error("need --target or --all")
    dest = target_dest(args.target, args.out_root, args.out)
    return write_or_check(EMITTERS[args.target](spec), dest, args.check)


if __name__ == "__main__":
    sys.exit(main())
